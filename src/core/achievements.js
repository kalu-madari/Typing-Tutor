export const checkAchievements = (store, completedLessonsCount, perfectLessonsCount, showToast) => {
  const { bestWpm, streak, totalTypedChars, unlockedAchievements, unlockAchievement } = store;

  ACHIEVEMENTS_LIST.forEach((achievement) => {
    if (unlockedAchievements.includes(achievement.id)) return; // Already unlocked

    let conditionMet = false;

    // Check conditions based on category and ID
    if (achievement.category === 'speed') {
      const targetWpm = parseInt(achievement.id.split('-')[1], 10);
      if (bestWpm >= targetWpm) conditionMet = true;
    } 
    else if (achievement.category === 'lessons') {
      const targetLessons = parseInt(achievement.id.split('-')[1], 10);
      if (completedLessonsCount >= targetLessons) conditionMet = true;
    }
    else if (achievement.category === 'streak') {
      const targetStreak = parseInt(achievement.id.split('-')[1], 10);
      if (streak >= targetStreak) conditionMet = true;
    }
    else if (achievement.category === 'accuracy') {
      const targetPerfect = parseInt(achievement.id.split('-')[2], 10);
      if (perfectLessonsCount >= targetPerfect) conditionMet = true;
    }
    else if (achievement.category === 'volume') {
      const rawTarget = achievement.id.split('-')[1];
      let targetChars = 0;
      if (rawTarget.endsWith('k')) targetChars = parseFloat(rawTarget) * 1000;
      else if (rawTarget.endsWith('m')) targetChars = parseFloat(rawTarget) * 1000000;
      if (totalTypedChars >= targetChars) conditionMet = true;
    }

    if (conditionMet) {
      unlockAchievement(achievement.id);
      if (showToast) {
        showToast(`${achievement.icon} Achievement Unlocked: ${achievement.title}`, 'success');
      }
    }
  });
};
